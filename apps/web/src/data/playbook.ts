/**
 * 商談ナビの台本。
 *
 * **生成AIは使わない。** フェーズ8と同じ理由で、APIキーを静的サイトに置けない。
 * それ以上に、営業の現場で読み上げる言葉は**人がレビューできる**必要がある。
 * 同じ状況には必ず同じ助言が出て、電波が無くても動き、誰が言っても同じ内容になる。
 *
 * 文言の方針:
 *
 * 1. **そのまま声に出せる文にする。** 「〜を訴求」ではなく「〜と言う」。
 *    素人が読み上げて成立しない台本は、現場で使われない。
 * 2. **なぜそう言うのかを必ず添える。** 台本だけ渡すと棒読みになる。
 *    根拠が分かれば自分の言葉に変えられる。
 * 3. **押し売りの型は入れない。** このアプリは安くならないお客様に
 *    「ご負担増」と正直に出す。台本だけ煽るのは筋が通らない。
 * 4. **断定しない。** 「絶対に安くなる」は不実告知になりうる。
 */

/** ヒアリングの回答。個人を特定する項目は置かない（CLAUDE.md ルール9） */
