import { Script } from './playbook'

/**
 * 「なぜ安くなるのか」への答え。
 *
 * **お客様が聞きたいのは、単価表の内訳ではない。**
 * 「第3段階の単価が2.71円安いからです」は正確だが、答えになっていない。
 * この質問の中身は、たいてい次のどれかである。
 *
 *   ① 電気の質が落ちるのではないか
 *   ② 安いのには裏があるのではないか
 *   ③ そもそも、なぜ電気の会社を選べるのか
 *
 * だから**仕組みから話す**。①を先に消してから②③に答える順にしてある。
 * 内訳の数字は「証拠」として最後に出す。先に出すと、ただの数字合戦になる。
 *
 * ⚠️ ここに書いてよいのは、**確かめられる事実だけ**。
 * 「広告費をかけていないから安い」「組合員に還元しているから安い」といった
 * JAでんきの事業上の理由は、出典を持っていないので書かない（CLAUDE.md ルール4）。
 * 言えるのは「料金表がこうなっている」という事実まで。
 */

export interface SwitchingStep {
  heading: string
  script: Script
}

export const SWITCHING: SwitchingStep[] = [
  {
    heading: '① まず、変わらないものをお伝えする',
    script: {
      say: [
        '電気そのものは、いまと何も変わりません。',
        '同じ電線を通って、同じ電気が届きます。',
        '停電したときに直しに来るのも、いままでと同じ中国電力ネットワークです。',
        '工事も、立ち会いも、原則ありません。'
      ],
      why:
        '**「なぜ安いのか」と聞かれたら、まず不安を消す。** 多くの場合、この質問は' +
        '「安い電気は品質が悪いのでは」という心配から出ている。' +
        '仕組みの説明を先にすると、その心配を抱えたまま聞くことになって頭に入らない。',
      avoid: ['いきなり単価の話を始めること']
    }
  },
  {
    heading: '② 何が変わるのかをお伝えする',
    script: {
      say: [
        '変わるのは、電気を「いくらで請求するか」を決める会社だけです。',
        '2016年に電気の小売りが自由化されまして、それ以来、どの会社から買うかを選べるようになりました。',
        'JAでんきは、その選べる会社のひとつです。'
      ],
      why:
        '発電・送配電・小売の3つに分かれていて、切り替わるのは**小売だけ**。' +
        'この構造を一度言っておくと、あとの説明が全部つながる。' +
        '「電気の会社を変える」ではなく「請求する会社を変える」と言うほうが、実態に近い。'
    }
  },
  {
    heading: '③ なぜ安くなるのかをお伝えする',
    script: {
      say: [
        '電気代は、毎月の基本になる料金と、使った分の単価とで決まります。',
        'JAでんきは、その料金表そのものが中国電力より安く作られています。',
        'どちらの料金表も公開されていますので、こうして並べて比べられます。'
      ],
      why:
        '**言えるのはここまで。** JAでんきがなぜその価格にできるのか、という事業の' +
        '事情までは、出典を持っていないのでお答えしない。' +
        '「たぶん広告費をかけていないから」などと補うと、それは推測であって、' +
        '後で違っていたときに信用を失う。' +
        '料金表が公開されていて比べられる、という事実のほうが強い。',
      avoid: [
        '「JAは営利目的ではないので安いんです」など、確かめていない理由を足すこと',
        '他社の悪口で説明すること'
      ]
    }
  }
]

